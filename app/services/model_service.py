import logging
import pickle
import threading
from pathlib import Path

import numpy as np
from tensorflow.keras.models import load_model
from tensorflow.keras.preprocessing.sequence import pad_sequences

from app.core.config import MODEL_DIR, MODEL_FILE, TOKENIZER_FILE, MAX_LEN_FILE
from app.services.text_utils import clean_text, format_generated_text

logger = logging.getLogger(__name__)


class ModelService:
    """Loads model artifacts once and performs GRU next-token sampling."""

    def __init__(self) -> None:
        self.model = None
        self.tokenizer = None
        self.max_len = None
        self._predict_lock = threading.Lock()

    @property
    def is_loaded(self) -> bool:
        return self.model is not None and self.tokenizer is not None and self.max_len is not None

    def load(self) -> None:
        model_path = MODEL_DIR / MODEL_FILE
        tokenizer_path = MODEL_DIR / TOKENIZER_FILE
        max_len_path = MODEL_DIR / MAX_LEN_FILE
        for path in (model_path, tokenizer_path, max_len_path):
            if not path.is_file():
                raise FileNotFoundError(f"Required model artifact not found: {path}")

        logger.info("Loading GRU model from %s", model_path)
        # compile=False is appropriate for inference; optimizer state is not needed.
        model = load_model(model_path, compile=False)
        # Pickle files must only be loaded from trusted sources. These artifacts are
        # generated by this project's own Colab training notebook.
        with tokenizer_path.open("rb") as f:
            tokenizer = pickle.load(f)
        with max_len_path.open("rb") as f:
            max_len = int(pickle.load(f))

        output_size = int(model.output_shape[-1])
        if max_len < 1:
            raise ValueError("max_len.pkl must contain a positive integer")
        if output_size < 2:
            raise ValueError(f"Unexpected model output size: {output_size}")

        self.model = model
        self.tokenizer = tokenizer
        self.max_len = max_len
        logger.info(
            "Model ready: input_length=%s, output_tokens=%s, parameters=%s",
            self.max_len, output_size, self.model.count_params()
        )

    def generate(
        self,
        prompt: str,
        sentence_count: int = 4,
        max_words_per_sentence: int = 20,
        max_new_tokens: int = 120,
        temperature: float = 0.8,
        top_k: int = 8,
    ) -> str:
        if not self.is_loaded:
            raise RuntimeError("Model is not loaded")
        if temperature <= 0:
            raise ValueError("temperature must be greater than zero")

        normalized = clean_text(prompt)
        generated_tokens = normalized.split()
        if not generated_tokens:
            raise ValueError("Please enter a prompt containing English letters or numbers.")

        sentence_endings = {".", "!", "?"}
        other_punctuation = {",", ";", ":"}
        sentence_count_generated = 0
        words_in_current_sentence = 0
        for token in reversed(generated_tokens):
            if token in sentence_endings:
                break
            if token not in other_punctuation:
                words_in_current_sentence += 1

        oov_id = self.tokenizer.word_index.get("<OOV>")
        output_size = int(self.model.output_shape[-1])
        rng = np.random.default_rng()

        for _ in range(max_new_tokens):
            context = " ".join(generated_tokens[-self.max_len:])
            sequence = self.tokenizer.texts_to_sequences([context])[0]
            # Training notebook used padding="post" and truncating="pre".
            # Keep inference preprocessing consistent with training.
            padded = pad_sequences(
                [sequence], maxlen=self.max_len, padding="post", truncating="pre"
            )

            # Protect model inference from simultaneous calls in multi-request workers.
            with self._predict_lock:
                predictions = self.model(padded, training=False).numpy()[0]
            probabilities = np.asarray(predictions, dtype=np.float64)
            probabilities[0] = 0.0  # padding token
            if oov_id is not None and 0 <= int(oov_id) < len(probabilities):
                probabilities[int(oov_id)] = 0.0
            if len(probabilities) > output_size:
                probabilities = probabilities[:output_size]

            # Temperature scaling is applied to log probabilities, then top-k sampling.
            logits = np.log(np.maximum(probabilities, 1e-12)) / temperature
            k = min(top_k, len(logits))
            if k < 1:
                break
            candidate_ids = np.argpartition(logits, -k)[-k:]
            candidate_logits = logits[candidate_ids]
            candidate_probs = np.exp(candidate_logits - np.max(candidate_logits))
            total = candidate_probs.sum()
            if not np.isfinite(total) or total <= 0:
                break
            candidate_probs /= total
            next_id = int(rng.choice(candidate_ids, p=candidate_probs))
            next_token = self.tokenizer.index_word.get(next_id, "")
            if not next_token or next_token == "<OOV>":
                continue

            generated_tokens.append(next_token)
            if next_token in sentence_endings:
                sentence_count_generated += 1
                words_in_current_sentence = 0
                if sentence_count_generated >= sentence_count:
                    break
            elif next_token not in other_punctuation:
                words_in_current_sentence += 1
                if words_in_current_sentence >= max_words_per_sentence:
                    generated_tokens.append(".")
                    sentence_count_generated += 1
                    words_in_current_sentence = 0
                    if sentence_count_generated >= sentence_count:
                        break

        return format_generated_text(generated_tokens)
